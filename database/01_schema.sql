-- Campus Skill Exchange Programme
-- Run in Supabase SQL Editor. Uses PostgreSQL identity columns and constraints.

create table if not exists public.students (
  student_id bigint generated by default as identity primary key,
  auth_user_id uuid unique references auth.users(id) on delete set null,
  roll_number text not null unique,
  full_name text not null,
  email text not null unique,
  phone text,
  department text not null,
  year_of_study smallint not null check (year_of_study between 1 and 8),
  section text,
  bio text,
  availability text not null default 'weekdays' check (availability in ('weekdays','weekends','evenings','flexible')),
  credits integer not null default 10 check (credits >= 0),
  joined_at timestamptz not null default now(),
  account_status text not null default 'active' check (account_status in ('active','inactive','suspended'))
);

create table if not exists public.skill_categories (
  category_id bigint generated by default as identity primary key,
  category_name text not null unique,
  description text
);

create table if not exists public.skills (
  skill_id bigint generated by default as identity primary key,
  category_id bigint not null references public.skill_categories(category_id) on delete restrict,
  skill_name text not null unique,
  description text
);

create table if not exists public.student_skills (
  student_skill_id bigint generated by default as identity primary key,
  student_id bigint not null references public.students(student_id) on delete cascade,
  skill_id bigint not null references public.skills(skill_id) on delete restrict,
  proficiency_level text not null check (proficiency_level in ('beginner','intermediate','advanced','expert')),
  experience_years numeric(4,1) not null default 0 check (experience_years >= 0),
  teaching_mode text not null default 'either' check (teaching_mode in ('online','in_person','either')),
  verified boolean not null default false,
  unique (student_id, skill_id)
);

create table if not exists public.wanted_skills (
  wanted_skill_id bigint generated by default as identity primary key,
  student_id bigint not null references public.students(student_id) on delete cascade,
  skill_id bigint not null references public.skills(skill_id) on delete restrict,
  target_level text not null check (target_level in ('beginner','intermediate','advanced','expert')),
  priority smallint not null default 3 check (priority between 1 and 5),
  learning_goal text,
  unique (student_id, skill_id)
);

create table if not exists public.exchange_requests (
  request_id bigint generated by default as identity primary key,
  sender_id bigint not null references public.students(student_id) on delete cascade,
  receiver_id bigint not null references public.students(student_id) on delete cascade,
  offered_skill_id bigint not null references public.skills(skill_id) on delete restrict,
  requested_skill_id bigint not null references public.skills(skill_id) on delete restrict,
  request_message text,
  requested_at timestamptz not null default now(),
  responded_at timestamptz,
  status text not null default 'pending' check (status in ('pending','accepted','rejected','cancelled')),
  check (sender_id <> receiver_id),
  check (offered_skill_id <> requested_skill_id),
  check ((status = 'pending' and responded_at is null) or (status <> 'pending'))
);

create table if not exists public.skill_exchanges (
  exchange_id bigint generated by default as identity primary key,
  request_id bigint not null unique references public.exchange_requests(request_id) on delete restrict,
  student_one_id bigint not null references public.students(student_id) on delete cascade,
  student_two_id bigint not null references public.students(student_id) on delete cascade,
  skill_one_id bigint not null references public.skills(skill_id) on delete restrict,
  skill_two_id bigint not null references public.skills(skill_id) on delete restrict,
  start_date date not null,
  end_date date,
  exchange_status text not null default 'active' check (exchange_status in ('scheduled','active','completed','cancelled','paused')),
  check (student_one_id <> student_two_id),
  check (end_date is null or end_date >= start_date)
);

create table if not exists public.sessions (
  session_id bigint generated by default as identity primary key,
  exchange_id bigint not null references public.skill_exchanges(exchange_id) on delete cascade,
  mentor_id bigint not null references public.students(student_id) on delete cascade,
  learner_id bigint not null references public.students(student_id) on delete cascade,
  skill_id bigint not null references public.skills(skill_id) on delete restrict,
  session_date timestamptz not null,
  duration_minutes smallint not null check (duration_minutes between 15 and 480),
  topic text not null,
  meeting_mode text not null check (meeting_mode in ('online','in_person')),
  session_status text not null default 'scheduled' check (session_status in ('scheduled','completed','cancelled','missed')),
  notes text,
  check (mentor_id <> learner_id)
);

create table if not exists public.reviews (
  review_id bigint generated by default as identity primary key,
  exchange_id bigint not null references public.skill_exchanges(exchange_id) on delete cascade,
  reviewer_id bigint not null references public.students(student_id) on delete cascade,
  reviewed_student_id bigint not null references public.students(student_id) on delete cascade,
  rating smallint not null check (rating between 1 and 5),
  comment text,
  created_at timestamptz not null default now(),
  check (reviewer_id <> reviewed_student_id),
  unique (exchange_id, reviewer_id, reviewed_student_id)
);

create table if not exists public.notifications (
  notification_id bigint generated by default as identity primary key,
  student_id bigint not null references public.students(student_id) on delete cascade,
  notification_type text not null,
  title text not null,
  message text not null,
  is_read boolean not null default false,
  created_at timestamptz not null default now()
);

create index if not exists idx_skills_category on public.skills(category_id);
create index if not exists idx_student_skills_skill on public.student_skills(skill_id);
create index if not exists idx_student_skills_student on public.student_skills(student_id);
create index if not exists idx_wanted_skills_skill on public.wanted_skills(skill_id);
create index if not exists idx_wanted_skills_student on public.wanted_skills(student_id);
create index if not exists idx_requests_receiver_status on public.exchange_requests(receiver_id, status);
create index if not exists idx_requests_sender on public.exchange_requests(sender_id);
create index if not exists idx_exchanges_students on public.skill_exchanges(student_one_id, student_two_id);
create index if not exists idx_sessions_exchange_date on public.sessions(exchange_id, session_date);
create index if not exists idx_reviews_reviewed_student on public.reviews(reviewed_student_id);
create index if not exists idx_notifications_student_unread on public.notifications(student_id, created_at desc) where is_read = false;

grant usage on schema public to anon, authenticated;
grant select, insert, update, delete on all tables in schema public to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;

-- ─────────────────────────────────────────────────────────────────────────────
-- Row-Level Security (RLS) Policies
-- Students can browse active profiles/skills, but may only mutate their own
-- listings, requests, sessions, and reviews (linked via auth.uid()).
-- ─────────────────────────────────────────────────────────────────────────────

create or replace function public.current_student_id()
returns bigint
language sql
stable
security definer
as $$
  select student_id from public.students where auth_user_id = auth.uid() limit 1;
$$;

alter table public.students enable row level security;
alter table public.student_skills enable row level security;
alter table public.wanted_skills enable row level security;
alter table public.exchange_requests enable row level security;
alter table public.skill_exchanges enable row level security;
alter table public.sessions enable row level security;
alter table public.reviews enable row level security;
alter table public.notifications enable row level security;

-- Public/authenticated read access for campus discovery
create policy "students_select_all" on public.students for select using (true);
create policy "students_update_own" on public.students for update to authenticated
  using (auth_user_id = auth.uid()) with check (auth_user_id = auth.uid());

create policy "student_skills_select_all" on public.student_skills for select using (true);
create policy "student_skills_manage_own" on public.student_skills for all to authenticated
  using (student_id = public.current_student_id())
  with check (student_id = public.current_student_id());

create policy "wanted_skills_select_all" on public.wanted_skills for select using (true);
create policy "wanted_skills_manage_own" on public.wanted_skills for all to authenticated
  using (student_id = public.current_student_id())
  with check (student_id = public.current_student_id());

create policy "exchange_requests_select_involved" on public.exchange_requests for select to authenticated
  using (sender_id = public.current_student_id() or receiver_id = public.current_student_id());
create policy "exchange_requests_insert_sender" on public.exchange_requests for insert to authenticated
  with check (sender_id = public.current_student_id());
create policy "exchange_requests_update_involved" on public.exchange_requests for update to authenticated
  using (sender_id = public.current_student_id() or receiver_id = public.current_student_id());

create policy "skill_exchanges_select_involved" on public.skill_exchanges for select to authenticated
  using (student_one_id = public.current_student_id() or student_two_id = public.current_student_id());
create policy "skill_exchanges_manage_involved" on public.skill_exchanges for all to authenticated
  using (student_one_id = public.current_student_id() or student_two_id = public.current_student_id())
  with check (student_one_id = public.current_student_id() or student_two_id = public.current_student_id());

create policy "sessions_select_involved" on public.sessions for select to authenticated
  using (mentor_id = public.current_student_id() or learner_id = public.current_student_id());
create policy "sessions_manage_involved" on public.sessions for all to authenticated
  using (mentor_id = public.current_student_id() or learner_id = public.current_student_id())
  with check (mentor_id = public.current_student_id() or learner_id = public.current_student_id());

create policy "reviews_select_all" on public.reviews for select using (true);
create policy "reviews_insert_own" on public.reviews for insert to authenticated
  with check (reviewer_id = public.current_student_id());

create policy "notifications_manage_own" on public.notifications for all to authenticated
  using (student_id = public.current_student_id())
  with check (student_id = public.current_student_id());
